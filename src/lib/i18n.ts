function preserveOuterWhitespace(source: string, translated: string) {
  const leading = source.match(/^\s*/)?.[0] ?? "";
  const trailing = source.match(/\s*$/)?.[0] ?? "";
  return `${leading}${translated}${trailing}`;
}

function preserveUppercase(source: string, translated: string) {
  const letters = source.replace(/[^A-Za-zÀ-ÿ]/g, "");
  return letters && letters === letters.toLocaleUpperCase("pt-BR") ? translated.toLocaleUpperCase("en-US") : translated;
}

function translateDynamicText(value: string): string {
  const unread = value.match(/^(\d+) não lida\(s\)$/i);
  if (unread) return `${unread[1]} unread`;

  const records = value.match(/^(\d+) registro\(s\)$/i);
  if (records) return `${records[1]} record(s)`;

  const sessions = value.match(/^(\d+) sessão\(ões\)$/i);
  if (sessions) return `${sessions[1]} session(s)`;

  const agentsDisplayed = value.match(/^(\d+) de (\d+) agente\(s\) exibido\(s\)$/i);
  if (agentsDisplayed) return `${agentsDisplayed[1]} of ${agentsDisplayed[2]} agent(s) displayed`;

  const queuesDisplayed = value.match(/^(\d+) de (\d+) fila\(s\) exibida\(s\)$/i);
  if (queuesDisplayed) return `${queuesDisplayed[1]} of ${queuesDisplayed[2]} queue(s) displayed`;

  const page = value.match(/^Página (\d+) de (\d+)$/i);
  if (page) return `Page ${page[1]} of ${page[2]}`;

  const showing = value.match(/^Mostrando (\d+) a (\d+) de (\d+) registros$/i);
  if (showing) return `Showing ${showing[1]} to ${showing[2]} of ${showing[3]} records`;

  const displayed = value.match(/^(\d+) de (\d+) parceiro\(es\) exibido\(s\)$/i);
  if (displayed) return `${displayed[1]} of ${displayed[2]} partner(s) displayed`;

  const recordsWithTotal = value.match(/^(\d+) de (\d+) registro\(s\)$/i);
  if (recordsWithTotal) return `${recordsWithTotal[1]} of ${recordsWithTotal[2]} record(s)`;

  for (const [pattern, replacement] of COUNT_LABELS) {
    if (pattern.test(value)) return value.replace(pattern, replacement);
  }

  const loading = value.match(/^Carregando (.+?)(\.\.\.)?$/i);
  if (loading) {
    const target: string = translateUiText(loading[1], "en-US");
    return `Loading ${target}${loading[2] ?? ""}`;
  }

  const searching = value.match(/^Buscando (.+?)(\.\.\.)?$/i);
  if (searching) {
    const target: string = translateUiText(searching[1], "en-US");
    return `Searching ${target}${searching[2] ?? ""}`;
  }

  const updatedAgo = value.match(/^Atualizado há (.+)$/i);
  if (updatedAgo) return `Updated ${updatedAgo[1]} ago`;

  const updatedAt = value.match(/^Atualizado em (.+)$/i);
  if (updatedAt) return `Updated on ${updatedAt[1]}`;

  const monthYear = value.match(/^(janeiro|fevereiro|março|abril|maio|junho|julho|agosto|setembro|outubro|novembro|dezembro)[ /](\d{4})$/i);
  if (monthYear) return `${MONTHS[monthYear[1].toLocaleLowerCase("pt-BR")]} ${monthYear[2]}`;

  return value;
}

export function translateUiText(value: string, language: AppLanguage): string {
  if (language === "pt-BR" || !value.trim()) return value;

  const trimmed = value.trim();
  const direct = ENGLISH_TRANSLATIONS.get(trimmed);
  if (direct) return preserveOuterWhitespace(value, direct);

  const insensitive = CASE_INSENSITIVE_TRANSLATIONS.get(trimmed.toLocaleLowerCase("pt-BR"));
  if (insensitive) return preserveOuterWhitespace(value, preserveUppercase(trimmed, insensitive));

  const dynamic: string = translateDynamicText(trimmed);
  return dynamic === trimmed ? value : preserveOuterWhitespace(value, dynamic);
}
